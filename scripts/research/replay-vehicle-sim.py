"""Record V1 fixtures: the original SIM load scaling and derived fields.

For every installed GameData/Simulation/CarData/*.sim (86 files incl.
default.sim) this executes nfs5.exe Sim_Load from VA 0x49c82f (after the file
read, whose effect is memset(carSpecs, 0, 0x1c4) + memcpy of the 328 bytes)
through Sim_DeriveFields 0x49cb50 in Unicorn (scripts/research/vehicle_harness.py)
and dumps the whole 0x1c4-byte carSpecs struct as named i32/f32 columns.
Field meanings: docs/re/vehicle.md section 5 in the workspace root.

Default tuning (res = car+0x558, vehicle_harness.DEFAULT_TUNING):
- fe.txt `car[0].*` defaults as 16.16 ints: frontdownforce/reardownforce
  3276800 (res+0x114/0x118), brakebias 3276800 (res+0x11c), rideheight 0
  (res+0x120), suspensiontravel 0 (res+0x124), steeringtoe 0 (res+0x128),
  suspensionstiffness 65536 (res+0x134), front/rear tirepressure 2293760
  (res+0x13c/0x140), all gear ratios and FINALRATIO 0 (res+0xf0..0x110).
  With these the tuning factors are neutral except ride height: 0x49cb50
  overwrites sim+0x120 with rideheight·0.001 = 0.
- Zero, because their writers are unknown (vehicle.md open questions):
  res+0xc (drive factors ×1.05 when 0), res+0x518 (light mode), res+0x17c
  (cheat string; "SILSPD"/"ROLLEY" branches not taken).
- No parts: 20 zeroed part records (kind 0).
- res+0x2a8 is the model/AI-spec name (`<name>.ais` in 0x49ca30). It selects
  tyre type 2 (GT1/GT2/GT3/935), front weight 0.4675 (959) and skips parts
  (959/928/GT2/GT3). **Hypothesis:** the name per .sim is the matching
  AICarData file (model_name() below); only those six names change outputs.

    python scripts/research/replay-vehicle-sim.py --game-dir local/game \
        --out local/fixtures/vehicle-sim.tsv
"""
import argparse
import hashlib
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import vehicle_harness as vh  # noqa: E402

# Longest prefix first; values are AICarData/*.ais stems.
MODEL_PREFIXES = [
    ('356A', '356A'), ('356B', '356B'), ('356', '356'), ('550', '550a'), ('901', '901'),
    ('914', '914'), ('928', '928'), ('930T', '930t'), ('935', '935'), ('944', '944'),
    ('959', '959'), ('964', '964'), ('965T', '965t'), ('9936', '993'), ('993T', '993t'),
    ('993', '993'), ('996T', '996t'), ('996', '996'), ('GT1', 'Gt1'), ('GT2', 'Gt2'),
    ('GT3', 'Gt3'), ('boxster', 'boxster'), ('default', 'default'),
]


def model_name(stem):
    for prefix, name in MODEL_PREFIXES:
        if stem.startswith(prefix):
            return name
    raise KeyError(f'no model name for {stem}')


def record(game_dir):
    module, data = vh.load_module('nfs5.exe', game_dir)
    m = vh.Machine(module, data)
    sims = sorted((game_dir / 'GameData/Simulation/CarData').glob('*.sim'), key=lambda p: p.name)
    rows = []
    for path in sims:
        raw = path.read_bytes()
        model = model_name(path.stem)
        specs = vh.derive_specs(m, raw, model)
        rows.append([('file', path.name), ('model', model),
                     ('sim_sha256', hashlib.sha256(raw).hexdigest()[:16])] +
                    vh.unpack_fields(specs, vh.CARSPECS_FIELDS))
    return module, rows


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--game-dir', type=Path, default=vh.ROOT / 'local/game')
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    module, rows = record(args.game_dir)
    _, again = record(args.game_dir)
    if rows != again:
        raise RuntimeError('two runs differ')
    vh.write_tsv(args.out, rows, comments=[
        'V1 fixtures: nfs5.exe 0x49c82f..0x49cb50 on each installed .sim, default tuning, no parts;',
        'generated by scripts/research/replay-vehicle-sim.py (x87 control word 0x27f).'])
    print(f"{len(rows)} cars ({module['file']}), two runs identical -> {args.out}")


if __name__ == '__main__':
    main()
